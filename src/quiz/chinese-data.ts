/** 课号 → 单元。 */
export function unitOf(lesson: number): number {
  const ends = [3, 7, 10, 14, 16, 19, 23, 27];
  return ends.findIndex((e) => lesson <= e) + 1;
}

export function lessonName(lesson: number): string {
  return Number.isInteger(lesson) ? `第${lesson}课《${LESSONS[lesson]}》` : `第${unitOf(lesson)}单元语文园地`;
}

