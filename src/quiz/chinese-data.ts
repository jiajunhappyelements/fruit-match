export interface Shizi {
  lesson: number;
  char: string;
  pinyin: string;
  /** 课本蓝字 = 多音字，不单独考读音 */
  poly: boolean;
}

export const SHIZI: Shizi[] = SHIZI_RAW.flatMap(([lesson, line]) =>
  line.split(" ").map((tok) => {
    const char = [...tok][0];
    const rest = tok.slice(char.length);
    const poly = rest.endsWith("!");
    return { lesson, char, pinyin: poly ? rest.slice(0, -1) : rest, poly };
  }),
);

